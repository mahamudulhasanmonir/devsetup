import { OS, Tool, CATEGORIES } from "./tools";

export function generateMarkdown(
  selectedIds: Set<string>,
  os: OS
): string {
  const osLabel: Record<OS, string> = {
    ubuntu: "Ubuntu / Debian Linux",
    macos: "macOS",
    windows: "Windows 10/11",
  };

  const osEmoji: Record<OS, string> = {
    ubuntu: "🐧",
    macos: "🍎",
    windows: "🪟",
  };

  const now = new Date().toISOString().slice(0, 10);

  let md = `# 🛠️ Dev Environment Setup Script\n\n`;
  md += `> **Generated by [DevSetup](https://devsetup.vercel.app)** on ${now}  \n`;
  md += `> **Target OS:** ${osEmoji[os]} ${osLabel[os]}\n\n`;
  md += `---\n\n`;
  md += `## 📋 Instructions for AI Agent\n\n`;
  md += `You are a setup agent. Your task is to install and configure **only** the tools listed in this document on **${osLabel[os]}**.\n\n`;
  md += `**Rules:**\n`;
  md += `- Run commands **in order**, one section at a time.\n`;
  md += `- Do **not** install anything not listed here.\n`;
  md += `- If a command requires a restart or shell reload, do it before continuing.\n`;
  md += `- If a tool is already installed (check with its verify command), skip it gracefully.\n`;
  md += `- After all tools are installed, print a ✅ summary showing each tool's installed version.\n\n`;
  md += `---\n\n`;

  let hasAny = false;

  for (const cat of CATEGORIES) {
    const tools = cat.tools.filter((t) => selectedIds.has(t.id));
    if (tools.length === 0) continue;

    hasAny = true;
    md += `## ${cat.icon} ${cat.label}\n\n`;

    for (const tool of tools) {
      md += `### ${tool.name}\n\n`;
      md += `> ${tool.description}\n\n`;

      const cmds = tool.commands[os];
      if (!cmds || cmds.length === 0) {
        md += `> ⚠️ **No automated install available for ${osLabel[os]}.** Please install manually.\n\n`;
      } else {
        md += `\`\`\`${os === "windows" ? "powershell" : "bash"}\n`;
        md += cmds.join("\n");
        md += `\n\`\`\`\n\n`;
      }

      // Verify command
      if (tool.checkCmd?.[os]) {
        md += `**Verify:**\n\`\`\`${os === "windows" ? "powershell" : "bash"}\n${tool.checkCmd[os]}\n\`\`\`\n\n`;
      }

      if (tool.note) {
        md += `> 📝 **Note:** ${tool.note}\n\n`;
      }
    }
  }

  if (!hasAny) {
    md += `> No tools selected.\n`;
  }

  md += `---\n\n`;
  md += `## ✅ Post-Install Verification\n\n`;
  md += `After all installations are complete, run the following to confirm:\n\n`;
  md += `\`\`\`${os === "windows" ? "powershell" : "bash"}\n`;

  for (const cat of CATEGORIES) {
    const tools = cat.tools.filter((t) => selectedIds.has(t.id));
    for (const tool of tools) {
      if (tool.checkCmd?.[os]) {
        md += `echo "--- ${tool.name} ---" && ${tool.checkCmd[os]}\n`;
      }
    }
  }
  md += `echo "\\n✅ All checks done!"\n`;
  md += `\`\`\`\n\n`;

  md += `---\n\n`;
  md += `*Generated by [DevSetup](https://devsetup.vercel.app) · Share this file with any AI coding agent to get started.*\n`;

  return md;
}

export function getSelectedTools(selectedIds: Set<string>): Tool[] {
  return CATEGORIES.flatMap((c) => c.tools).filter((t) => selectedIds.has(t.id));
}
